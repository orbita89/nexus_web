export function formatMicros(us: number): string {
	return us >= 1000 ? `${(us / 1000).toFixed(1)} мс` : `${us} мкс`;
}

/** Доля 0–1 в проценты для полосок. */
export function pct(x: number): number {
	return Math.round(Math.min(1, Math.max(0, x)) * 100);
}
