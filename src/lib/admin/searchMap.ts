/** Что лежит в файле каталога индекса. */
export function describeFile(name: string): string {
	if (name === 'sidecar-entities.cols')
		return 'Слой Б: SortMeta, даты, балл и 8 готовых порядков сортировки (номера и позиции)';
	if (name === 'sidecar-entities.bin')
		return 'Слой Б: битовые карты мелких фильтров и таблицы подсказок — читаются в память';
	if (name === 'sidecar-people.cols')
		return 'Слой Б людей: известность и порядки по известности и имени';
	if (name === 'sidecar-people.bin')
		return 'Слой Б людей: видимые и основные роли — читаются в память';
	if (name === 'meta.json') return 'Список сегментов Tantivy';
	if (name.startsWith('.')) return 'Служебный файл Tantivy (блокировка, учёт файлов)';
	if (name === 'schema-version') return 'Версия схемы индекса (сменилась — нужна перестройка)';
	const ext = name.split('.').pop() ?? '';
	return FILE_KINDS[ext] ?? 'Файл сегмента Tantivy';
}

